#!/usr/bin/env python3
"""Generate local CSS artwork; --check verifies the checked-in runtime bundle."""
from pathlib import Path
from urllib.parse import quote
import argparse, re, json, hashlib
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
source=ROOT/'assets/file-icons'
provenance=json.loads((source/'PROVENANCE.json').read_text())
files=sorted(source.glob('*.svg'))
if len(files)!=54 or {p.stem for p in files}!=set(provenance['icons']):raise SystemExit('Expected54 source SVGs and provenance records')
lines=['/* Generated by tools/build-file-icons.py. OpenIDEA Material Icons (Apache-2.0),',' * with modified folder emblems and original Composer artwork. See THIRD_PARTY_NOTICES.md.',' * Data URLs stay in this stylesheet: no network requests, SVG DOM or host calls per row. */']
for path in files:
    raw=path.read_text();svg=ET.fromstring(raw)
    if svg.tag!='{http://www.w3.org/2000/svg}svg' or svg.attrib.get('viewBox')!='0 0 16 16':raise SystemExit('Invalid icon '+path.name)
    record=provenance['icons'][path.stem]
    if record.get('sha256') and hashlib.sha256(path.read_bytes()).hexdigest()!=record['sha256']:raise SystemExit('Pinned icon changed: '+path.name)
    for el in svg.iter():
        if el.tag.split('}')[-1] not in ['svg','g','path','rect','circle','ellipse','line','polyline','polygon','text']:raise SystemExit('Unexpected SVG element in '+path.name)
        for key,value in el.attrib.items():
            if key.lower().startswith('on') or key.split('}')[-1] in ['href','style'] or 'url(' in value.lower():raise SystemExit('Unexpected SVG attribute in '+path.name)
    raw=re.sub(r'<!--.*?-->','',raw,flags=re.S).strip()
    encoded=quote(raw,safe='')
    lines.append(f'.file-kind-icon[data-icon="{path.stem}"] {{ background-image: url("data:image/svg+xml,{encoded}"); }}')
# Neutral paper icons remain readable in both host themes. Colored kinds use the
# original consistent Material palette; no per-row theme listeners are needed.
for name in ['file','text','log']:
    raw=(source/(name+'.svg')).read_text().strip()
    # The upstream neutral color varies by icon. Override only neutral fills.
    raw=re.sub(r'#[0-9a-fA-F]{6}',lambda m:'#aab5c6' if m[0].lower() not in ['#ffffff'] else m[0],raw)
    encoded=quote(raw,safe='')
    lines.append(f':root[data-theme="dark"] .file-kind-icon[data-icon="{name}"] {{ background-image: url("data:image/svg+xml,{encoded}"); }}')
output='\n'.join(lines)+'\n';target=ROOT/'web/file-icons.css'
if args.check:
    if not target.exists() or target.read_text()!=output:raise SystemExit('Icon CSS is stale; run python3 tools/build-file-icons.py')
    print('54 icon sources validated; runtime CSS is current')
else:
    target.write_text(output);print(f'Generated54 kinds, {len(output.encode())} bytes')
